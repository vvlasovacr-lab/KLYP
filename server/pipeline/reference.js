// ЭТАЛОН МОНТАЖА.
//
// Модель знает теорию монтажа, но не знает, на что равняемся мы. Пока
// ей не показали образец, она собирала «правильный вообще» ролик, а не
// такой, какие делают в этой нише.
//
// Здесь шесть кадров из ролика, который мы считаем эталоном, и разбор
// того, что в них важно. Кадры уходят в каждый запрос вместе с кадрами
// самого заказа: модель видит и образец, и материал, и сама решает, как
// применить одно к другому.
//
// Шесть кадров весят около двух тысяч токенов — примерно тридцать копеек
// на ролик. Дешевле любой правки.

import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DIR = path.resolve(HERE, '..', '..', 'reference');

let cached = null;

export const referenceFrames = async () => {
	if (cached) return cached;

	const out = [];
	for (let i = 0; i < 6; i++) {
		const bytes = await fs.readFile(path.join(DIR, `${i}.jpg`)).catch(() => null);
		if (bytes?.length) out.push(bytes.toString('base64'));
	}

	cached = out;
	return out;
};

// Разбор эталона. Пишется от того, что видно в кадрах, — по порядку,
// в котором они уходят в запрос.
export const REFERENCE = `## Эталон, на который равняемся

Сначала тебе показывают шесть кадров из чужого ролика. Это образец
уровня, к которому мы идём. Разбери его — дальше пойдут кадры того
ролика, который монтируешь ты.

**Кадр 1 — плашка.** Заголовок набран не одним кеглем, а вперемешку:
главные слова крупные, служебные — мелкие на цветной подложке.
«КАК БЫСТРО» крупно, «находить» мелко на красном прямоугольнике,
«ЗАЛЕТАЮЩИЕ» крупно, «идеи» снова мелко на красном. Получается не
строка, а собранный плакат. Держится он около трёх секунд.

Вот почему это работает: глаз цепляется за перепад размеров. Ровная
строка одного кегля читается как титр в новостях и пролистывается.

**Кадр 2 — ударное слово.** «2 ОЧЕНЬ» — заглавными, золотом, крупно.
Так выделено одно-два слова на всю фразу, не больше.

**Кадр 3 — обычный субтитр.** «ДЛЯ ПАРСИНГА ПОПУЛЯРНОГО КОНТЕНТА» —
белым, спокойно, в три строки. Заметно мельче ударного. Разница в
размере между обычным и ударным — вдвое.

Запомни главное: размер — это и есть ударение. Не цвет и не эффект.
Служебные слова идут мелко, суть — крупно. Если всё одного размера,
ролик читается ровно и скучно, как бы ни был хорош текст.

**Кадр 4 — врезка во весь экран.** Здесь это запись экрана того, о чём
идёт речь. Важно не то, откуда взята картинка, а что она показывает
ровно то, что человек называет голосом, и появляется в тот момент,
когда он это называет.

Клип из нашей библиотеки годится не хуже: если речь про деньги — счётчик
купюр, про долги — падающий график. Бери из библиотеки смело, это не
запасной вариант. Свои кадры клиента, когда они есть, ставь туда, где
показать надо именно его — его экран, его объект, его документ.

**Кадр 5 — так делать не надо.** Здесь весь экран залит цветом, на нём
одно слово. Мы этот приём не используем: однотонная заливка посреди
ролика выглядит дёшево, а субтитры поверх неё читаются как надпись на
пустой стене. Если нужна пауза для глаза — ставь врезку, там есть
движение и картинка.

**Кадр 6 — врезка углом.** Лицо остаётся во весь кадр, а в верхнем углу
всплывает небольшая карточка — скриншот профиля. Так показывают
доказательство, не бросая говорящего.

**Чего в эталоне НЕТ.** Лицо снято одним планом почти без склеек.
Ритм держится не нарезкой говорящего, а текстом и врезками. Не надо
рубить лицо каждые полторы секунды: это выглядит суетливо и выдаёт
машинный монтаж.

**Врезка — это всегда движущаяся картинка.** Никаких заливок цветом,
никаких пустых фонов под текст. Если в этом месте нечего показать —
не показывай ничего, оставь лицо. Пустой цветной кадр хуже, чем его
отсутствие.

**Как это применить.** Найди в речи: одну сильную мысль на плашку;
слова, которые надо ударить размером; моменты, где человек называет
что-то показываемое — туда врезку. Остальное оставь лицу.

И последнее, самое важное. Это образец уровня, а не шаблон для
копирования. Не надо повторять его один в один: другой ролик, другая
речь, другой человек. Бери приёмы — размер как ударение, вставку в
нужный момент, паузу на переломе — и собирай из них своё под этот
материал. Ролик, слепленный по чужой схеме, видно сразу.`;
