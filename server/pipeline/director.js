// Режиссёр монтажа.
//
// До этого решения принимали правила: слово длиннее одиннадцати букв —
// значит важное, в реплике встретилось «договор» — значит показать бумаги.
// Правила не знают, о чём ролик: они подсветят «долговую», потому что она
// длинная, а не потому что в ней суть.
//
// Здесь ту же работу делает модель. Ей уходит расшифровка с таймингами
// и список наших врезок; обратно — что подсветить, где вставить клип
// и каким заголовком открыть.
//
// Модель может не ответить: кончились деньги на счету, сеть моргнула,
// вернулся мусор. Тогда возвращается null, и монтаж собирается по старым
// правилам — ролик выходит в любом случае.

import Anthropic from '@anthropic-ai/sdk';
import {config, hasModel} from './../config.js';

// Что лежит в библиотеке врезок. Описания нужны модели, а не нам:
