const PROMPT = `Ты монтируешь вертикальные ролики для соцсетей.

На вход — расшифровка речи с секундами. На выход — разметка монтажа.

## Плашка

Первые секунды ролика. Это крючок: человек листает ленту и должен
остановиться. Бери самое сильное из того, что сказано в начале — цифру,
обещание, неожиданное утверждение. Не пересказывай, а вытаскивай.

От двух до четырёх строк, каждая до 19 знаков. Слова только те, что
реально звучат в ролике — придумывать нельзя.

## Акценты

Слова, которые в кадре встанут крупно поверх остального текста.
Подсвечивай то, на чём держится мысль: цифры, суммы, суть обещания,
суть угрозы. Не подсвечивай служебные слова и не бери слово только за то,
что оно длинное.

Ритм: примерно одно слово на каждые три-четыре секунды. Подряд идущие
слова не подсвечивают — между акцентами должно пройти хотя бы две секунды.

Цвет: gold — про выгоду, деньги, результат. danger — про потерю, риск,
запрет, наказание.

Секунда и текст слова берутся из расшифровки без изменений.

## Врезки

Клип поверх говорящего на две-три секунды. Ставится там, где картинка
усиливает сказанное: речь про самолёт — самолёт, речь про наручники —
наручники. Если подходящего клипа нет, врезку не ставить: неуместная
картинка хуже её отсутствия.

Не чаще одной врезки на семь секунд. Один и тот же клип дважды за ролик
не использовать. В первые четыре и последние четыре секунды не ставить —
там плашка и призыв.

## Жанр

expose — разоблачение, «вас обманывают»
hook — цепляющая история
offer — предложение, продажа
breakdown — разбор, объяснение по шагам
case — история из практики
myths — развенчание заблуждений
warmup — спокойный разговор`;

// Расшифровка для модели: секунда, текст реплики, и отдельно каждое
// слово с его секундой — иначе она не сможет сослаться на слово точно.
const transcript = (chunks) =>
	chunks
		.map((chunk) => {
			const words = chunk.words.map((w) => `${w.text}@${w.start.toFixed(1)}`).join(' ');
			return `[${chunk.start.toFixed(1)}] ${words}`;
		})
		.join('\n');

let client = null;

export const direct = async ({chunks, duration}) => {
	if (!hasModel()) return null;
	if (!chunks?.length) return null;

	client ??= new Anthropic({apiKey: config.anthropic.apiKey});

	const clips = CLIPS.map((c) => `${c.file} — ${c.about}`).join('\n');

	const task =
		`Длительность ролика: ${duration.toFixed(1)} секунд.\n\n` +
		`Врезки, которые есть в библиотеке:\n${clips}\n\n` +
		`Расшифровка (в квадратных скобках — секунда начала реплики, ` +
		`через @ — секунда каждого слова):\n\n${transcript(chunks)}`;

	const started = Date.now();

	try {
		const answer = await client.messages.create({
			model: config.anthropic.model,
			max_tokens: 8000,
			system: PROMPT,
			thinking: {type: 'adaptive'},
			output_config: {
				effort: 'medium',
				format: {type: 'json_schema', schema: SHAPE},
			},
			messages: [{role: 'user', content: task}],
		});

		if (answer.stop_reason === 'refusal') {
			console.warn('  режиссёр: модель отказалась разбирать этот текст');
			return null;
		}

		const text = answer.content.find((block) => block.type === 'text')?.text;
		if (!text) return null;

		const plan = JSON.parse(text);
		plan.ms = Date.now() - started;
		plan.usage = {
			in: answer.usage.input_tokens,
			out: answer.usage.output_tokens,
		};
		return plan;
	} catch (err) {
		// Разметка по правилам никуда не делась — ролик соберётся и без модели.
		console.warn(`  режиссёр недоступен (${String(err.message).slice(0, 120)}), собираю по правилам`);
		return null;
	}
};
