// СЛОВА-ВЫКРИКИ.
// Пока такой активен, обычные субтитры молчат: на экране одно слово
// в кавычках. Ради него зритель и полезет в комментарии.
export const SHOUTS = [{from: 47.64, to: 48.66, text: 'ЧАТ'}];

export const shoutAt = (time) =>
	SHOUTS.find((s) => time >= s.from && time < s.to) ?? null;

export const isAccent = (time) =>
	ACCENTS.some(([from, to]) => time >= from && time < to);

// моменты, на которых камера делает короткий наезд
export const ACCENT_STARTS = ACCENTS.map(([from]) => from);
