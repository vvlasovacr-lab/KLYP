// ПОЧЕРК МОНТАЖА.
//
// Модель долго решала только, что показать: текст плашки, какие слова
// подсветить, какие врезки. А как это выглядит и движется, было наглухо
// зашито в компонентах — одинаково для всех роликов. Поэтому «сделай
// спокойно» и «сделай дерзко» давали одну и ту же картинку разного
// цвета, и монтаж выглядел шаблонным, хотя разметка каждый раз была
// новая.
//
// Здесь собраны рычаги, которые модель дёргает сама. Их читают и
// компоненты, и сборка плана — значения должны совпадать до буквы,
// поэтому они живут в одном файле, а не в трёх.

export const MANNER = {
	// Как ведут себя субтитры.
	//
	//   по-слову  — слово за словом, каждое во всю ширину. Держит
	//               внимание, но дробит длинную мысль
	//   по-фразе  — реплика целиком, читается спокойно
	//   караоке   — реплика висит, произносимое слово подсвечено
	//   крупно    — по два-три слова во весь кадр
	subs: 'по-слову',

	// Как приходит плашка: собирается словами, появляется разом,
	// набирается буквами или выезжает сбоку.
	titleIn: 'по-слову',

	// Темп склеек и зумов.
	pace: 'ровно',

	// Как входит врезка.
	brollIn: 'резко',

	// Сколько звуковых акцентов.
	sound: 'умеренно',
};

const ALLOWED = {
	subs: ['по-слову', 'по-фразе', 'караоке', 'крупно'],
	titleIn: ['по-слову', 'целиком', 'печать', 'выезд'],
	pace: ['медленно', 'ровно', 'быстро', 'рвано'],
	brollIn: ['резко', 'свистом', 'наплывом', 'стоп-кадром'],
	sound: ['тихо', 'умеренно', 'плотно'],
};

// Модель может не ответить вовсе — тогда собираем как раньше. Может
// вернуть значение, которого мы не знаем, — тогда берём наше: чужое
// слово в поле стиля означало бы, что компонент не нарисует ничего.
export const toManner = (asked) => {
	const out = {...MANNER};
	if (!asked || typeof asked !== 'object') return out;

	for (const key of Object.keys(ALLOWED)) {
		if (ALLOWED[key].includes(asked[key])) out[key] = asked[key];
	}
	return out;
};

// Темп решает, как часто резать и зумить. Множитель идёт к тому
// промежутку, который задан жанром: жанр говорит о плотности вообще,
// темп — об этом конкретном ролике.
export const PACE = {
	'медленно': {cut: 1.6, zoom: 0.7, punch: 0.8},
	'ровно': {cut: 1.0, zoom: 1.0, punch: 1.0},
	'быстро': {cut: 0.62, zoom: 1.3, punch: 1.15},
	// Рвано — те же частые склейки, но неравномерные: длинный план,
	// потом очередь коротких. Неравномерность даёт сам разброс.
	'рвано': {cut: 0.72, zoom: 1.2, punch: 1.35, uneven: 0.55},
};

// Сколько звука. Ноль означает тишину, а не «чуть тише»: в серьёзном
// разговоре о деньгах свист на каждом слове выглядит несерьёзно.
export const SOUND = {
	'тихо': 0.35,
	'умеренно': 1,
	'плотно': 1.6,
};
