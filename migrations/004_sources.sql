-- Несколько исходников в одном ролике.
--
-- Клиент снимает подводку, основную часть и концовку разными дублями,
-- а ролик хочет один. Раньше в заказ помещался ровно один файл.
--
-- Здесь лежит список загруженных файлов в том порядке, в каком клиент
-- их выбрал. Перед монтажом они склеиваются в один, и дальше по трубе
-- идёт привычный единственный исходник — поэтому source_path остаётся
-- на месте и хранит склейку.
ALTER TABLE videos ADD COLUMN IF NOT EXISTS sources JSONB;
